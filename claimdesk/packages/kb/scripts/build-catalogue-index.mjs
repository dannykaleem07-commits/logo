#!/usr/bin/env node
/**
 * Build packages/kb/data/vehicle-catalogue/index.json (TEMPLATES-VEHICLES-DESKTOP §D.1, §D.5): one
 * `CatalogueMakeSummary` row per make file, sorted by display name, so `listCatalogueMakes()` does not have to read
 * every make file. Plain Node ESM, no dependencies; the output is deterministic (no timestamps).
 *
 *   node packages/kb/scripts/build-catalogue-index.mjs            write index.json
 *   node packages/kb/scripts/build-catalogue-index.mjs --check    exit 1 when index.json is missing or out of date
 *   options: --dir <catalogue dir>
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const VEHICLE_TYPES = ['car', 'van', 'pickup', 'minibus', 'camper'];

/** Same summary as packages/kb/src/catalogue/load.ts `summariseMake`. */
export function summariseMakeFile(raw) {
  const models = Array.isArray(raw.models) ? raw.models : [];
  const froms = models.map((m) => m.years?.from).filter((n) => typeof n === 'number');
  const tos = models.map((m) => (m.years?.to === undefined ? null : m.years.to));
  return {
    slug: raw.slug,
    make: raw.make,
    dvlaNames: raw.dvlaNames ?? [],
    aliases: raw.aliases ?? [],
    modelCount: models.length,
    years: {
      from: froms.length ? Math.min(...froms) : 0,
      to: !tos.length || tos.some((t) => t === null) ? null : Math.max(...tos),
    },
    vehicleTypes: VEHICLE_TYPES.filter((t) => models.some((m) => m.vehicleType === t)),
  };
}

export function buildIndex(dir) {
  const makesDir = path.join(dir, 'makes');
  const rows = readdirSync(makesDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => {
      const raw = JSON.parse(readFileSync(path.join(makesDir, f), 'utf8'));
      if (raw.slug !== path.basename(f, '.json')) throw new Error(`makes/${f}: slug '${raw.slug}' does not match the file name`);
      return summariseMakeFile(raw);
    })
    .sort((a, b) => a.make.localeCompare(b.make, 'en-GB'));
  return {
    schemaVersion: 1,
    verification: {
      status: 'unverified',
      sourceNote: 'Generated by packages/kb/scripts/build-catalogue-index.mjs from makes/*.json; the make files are unverified reference data.',
    },
    makeCount: rows.length,
    modelCount: rows.reduce((n, r) => n + r.modelCount, 0),
    makes: rows,
  };
}

export function serialiseIndex(index) {
  // one make per line keeps diffs readable
  const head = JSON.stringify({ ...index, makes: undefined }, null, 1).replace(/\n}$/, '');
  return `${head},\n "makes": [\n${index.makes.map((r) => `  ${JSON.stringify(r)}`).join(',\n')}\n ]\n}\n`;
}

function main() {
  const argv = process.argv.slice(2);
  const here = path.dirname(fileURLToPath(import.meta.url));
  let dir = path.resolve(here, '../data/vehicle-catalogue');
  const di = argv.indexOf('--dir');
  if (di >= 0) dir = path.resolve(argv[di + 1]);
  const file = path.join(dir, 'index.json');
  const text = serialiseIndex(buildIndex(dir));
  if (argv.includes('--check')) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (current !== text) {
      console.error('index.json is missing or out of date — run node packages/kb/scripts/build-catalogue-index.mjs');
      process.exitCode = 1;
      return;
    }
    console.log('index.json is up to date');
    return;
  }
  writeFileSync(file, text);
  const index = JSON.parse(text);
  console.log(`wrote ${path.relative(process.cwd(), file)}: ${index.makeCount} makes, ${index.modelCount} models`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
