#!/usr/bin/env node
/* Compiles research/*.json (plus any extra JSON files passed as arguments) into app/data/oem.js. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'research');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => path.join(dir, f)).concat(process.argv.slice(2));
const vehicles = [];
for (const f of files) {
  const d = JSON.parse(fs.readFileSync(f, 'utf8'));
  const key = path.basename(f, '.json');
  const parts = {};
  for (const p of d.parts) {
    const k = p.code + '|' + (p.side || '');
    (parts[k] = parts[k] || []).push({
      oem: p.oem, description: p.description, notes: p.notes || '', price: p.price_gbp, priceSource: p.price_source || '',
      source: p.source_url || '', confidence: p.confidence || 'single-source'
    });
  }
  // confirmed entries first
  Object.values(parts).forEach((list) => list.sort((a, b) => (a.confidence === 'confirmed' ? -1 : 0) - (b.confidence === 'confirmed' ? -1 : 0)));
  vehicles.push({ key, make: d.vehicle.make, model: d.vehicle.model, generation: d.vehicle.generation, years: d.vehicle.years, notes: d.vehicle.notes || '', researched: d.researched || '', parts });
}
vehicles.sort((a, b) => (a.make + a.model).localeCompare(b.make + b.model));
const out = `/* GENERATED by tools/build-oem.js from research/*.json. Do not edit by hand. */\nwindow.OEM_VEHICLES = ${JSON.stringify(vehicles, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'app', 'data', 'oem.js'), out);
console.log(`Wrote ${vehicles.length} vehicles, ${vehicles.reduce((n, v) => n + Object.values(v.parts).flat().length, 0)} part numbers.`);
