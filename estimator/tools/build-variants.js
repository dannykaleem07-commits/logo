#!/usr/bin/env node
/* Compiles research/variants/*.json into app/data/variants.js (window.VARIANTS) for the exact-variant picker. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'research', 'variants');
const models = [];
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
    const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    for (const m of d.models || []) {
      if (!m.make || !m.model) continue;
      models.push({
        make: m.make, model: m.model, generation: m.generation || '', years: m.years || '', facelift: m.facelift || '',
        bodies: m.bodies || [], engines: (m.engines || []).filter((e) => e && e.badge), trims: m.trims || [], trims_by_period: m.trims_by_period || null, transmissions: m.transmissions || [],
        notes: [m.notes, m.verification].filter(Boolean).join(' '), status: m.status === 'verified' ? 'verified' : 'general-knowledge', sources: m.sources || [], file: f
      });
    }
  }
}
models.sort((a, b) => (a.make + a.model + a.years).localeCompare(b.make + b.model + b.years));
fs.writeFileSync(path.join(root, 'app', 'data', 'variants.js'), `/* GENERATED by tools/build-variants.js from research/variants/*.json. Do not edit by hand. */\nwindow.VARIANTS = ${JSON.stringify(models, null, 1)};\n`);
console.log(`Wrote ${models.length} model generations, ${models.reduce((n, m) => n + m.engines.length, 0)} engines, ${models.reduce((n, m) => n + m.trims.length, 0)} trims.`);
